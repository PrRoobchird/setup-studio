export function getStudioRank(fame: number): string {
  if (fame >= 300) return 'เจ้าสำนักอาร์ตติสท์';
  if (fame >= 180) return 'ตัวตึงพอร์ตโฟลิโอ';
  if (fame >= 90) return 'สายครีเอทีฟไฟแรง';
  if (fame >= 40) return 'นักออกแบบหน้าใหม่';
  return 'เด็กติวฝึกหัด';
}

